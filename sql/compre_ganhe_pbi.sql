WITH EM_LINHA AS (
    SELECT
        F.COD_PESQUISA_FORMULARIO,
        L.COD_REDE,
        L.DES_BANDEIRA,
        L.NOM_FANTASIA,
        L.END_LOGRADOURO,
        L.DES_UF,
        T.DATA,
        P.NOM_PESSOA AS PROMOTOR,
        P.SUPERVISOR,
        FP.DES_PERGUNTA,
        F.BI_ID_LOJA,
        F.BI_ID_PESSOA,
        COALESCE(FR.DES_RESPOSTA, FA.DES_ALTERNATIVA) AS DES_RESPOSTA
    FROM BI_F_FORMULARIO F

    INNER JOIN BI_D_FORMULARIO F1
        ON F1.BI_ID_FORMULARIO = F.BI_ID_FORMULARIO

    INNER JOIN BI_D_FORMULARIO_ALTERNATIVAS FA
        ON FA.BI_ID_FORMULARIO_ALTERNATIVAS = F.BI_ID_FORMULARIO_ALTERNATIVAS

    INNER JOIN BI_D_FORMULARIO_PERGUNTAS FP
        ON FP.BI_ID_FORMULARIO_PERGUNTAS = F.BI_ID_FORMULARIO_PERGUNTAS

    INNER JOIN BI_D_FORMULARIO_RESPOSTAS FR
        ON FR.BI_ID_FORMULARIO_RESPOSTAS = F.BI_ID_FORMULARIO_RESPOSTAS

    INNER JOIN BI_D_SKU S
        ON S.BI_ID_SKU = F.BI_ID_SKU

    INNER JOIN BI_D_PESSOA P
        ON P.BI_ID_PESSOA = F.BI_ID_PESSOA

    INNER JOIN BI_D_LOJA L
        ON L.BI_ID_LOJA = F.BI_ID_LOJA

    INNER JOIN BI_D_TEMPO T
        ON T.BI_ID_TEMPO = F.BI_ID_TEMPO

    WHERE F.COD_FORMULARIO = 16
      AND P.COD_PESSOA <> 1

      -- Remove as UFs amarelas no período de 05/01/2025 até 11/08/2026
      AND NOT (
          L.DES_UF IN ('BA', 'CE', 'DF', 'GO', 'MG', 'RJ', 'SC')
          AND T.DATA >= '20250105'
          AND T.DATA <  '20260812'
      )
)

SELECT
    DES_BANDEIRA AS BANDEIRA,
    NOM_FANTASIA AS LOJA,
    DES_UF,
    END_LOGRADOURO,
    DATA,
    PROMOTOR,
    SUPERVISOR,
    [ COMPRE E GANHE ATIVADO? ],
    ISNULL(
        [INFORME A QTD DE BRINDES ENTREGUES:],
        0
    ) AS [INFORME A QTD DE BRINDES ENTREGUES:],
    BI_ID_LOJA,
    BI_ID_PESSOA
FROM EM_LINHA

PIVOT (
    MAX(DES_RESPOSTA)
    FOR DES_PERGUNTA IN (
        [ COMPRE E GANHE ATIVADO? ],
        [INFORME A QTD DE BRINDES ENTREGUES:]
    )
) AS PVT;